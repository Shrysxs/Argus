// Compiles prompts/<agent>/<version>.md into src/prompts.generated.ts so the
// prompt text ships inside the bundle. Reading .md files from disk at runtime
// is unreliable on serverless hosts (files are not traced into the function),
// and a missing prompt must never silently fall back to a generic one.
//
// Run: npm run prompts -w @argus/agents
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const promptsDir = path.join(root, "prompts");

const entries = {};
for (const agent of fs.readdirSync(promptsDir).sort()) {
  const dir = path.join(promptsDir, agent);
  if (!fs.statSync(dir).isDirectory()) continue;
  for (const file of fs.readdirSync(dir).sort()) {
    if (!file.endsWith(".md")) continue;
    entries[`prompts/${agent}/${file}`] = fs.readFileSync(path.join(dir, file), "utf-8");
  }
}

const out = `// AUTO-GENERATED by scripts/generate-prompts.mjs — do not edit by hand.
// Edit the .md files under prompts/ (with a version bump) and re-run the script.

export const PROMPTS: Readonly<Record<string, string>> = ${JSON.stringify(entries, null, 2)};
`;

fs.writeFileSync(path.join(root, "src", "prompts.generated.ts"), out);
console.log(`Wrote ${Object.keys(entries).length} prompts to src/prompts.generated.ts`);
